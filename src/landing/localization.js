export function localizeScreenshot(shot, language) {
  if (language !== "ru") return shot;
  const copy = russianScreenshots[shot.file];
  return { ...shot, caption: `${copy.caption} — Site-12`, alt: copy.alt, shortCaption: copy.caption };
}

export function getLandingLabels(language) {
  return language === "ru"
    ? { pause: "Приостановить слайд-шоу", resume: "Продолжить слайд-шоу", enlarge: "Увеличить скриншот" }
    : { pause: "Pause slideshow", resume: "Resume slideshow", enlarge: "Enlarge screenshot" };
}

export function localizeLanding() {
  const url = new URL(window.location.href);
  const language = url.searchParams.get("lang") === "ru" ? "ru" : "en";
  document.documentElement.lang = language;

  for (const link of document.querySelectorAll("[data-language]")) {
    const target = new URL(url);
    target.searchParams.set("lang", link.dataset.language);
    link.href = target.href;
    link.setAttribute("aria-current", link.dataset.language === language ? "true" : "false");
  }
  if (language === "ru") {
    for (const [selector, html] of Object.entries(russianPage)) {
      document.querySelector(selector).innerHTML = html;
    }
    for (const [selector, attribute, value] of russianAttributes) {
      document.querySelector(selector).setAttribute(attribute, value);
    }
    document.querySelector(".language-switch").setAttribute("aria-label", "Язык страницы");
    document.title = "Baseload About";
    document.querySelector('meta[name="description"]').content = "BASELOAD — игра от первого лица о работе на старом термоядерном объекте. Играйте прямо в браузере: ничего скачивать не нужно.";
    document.querySelector('meta[property="og:title"]').content = document.title;
    document.querySelector('meta[property="og:description"]').content = "Браузерная игра об управлении объектом, который давно пора было закрыть.";
  }
  return language;
}
